_EN_RE = re.compile("|".join(re.escape(k) for k in sorted(EN, key=len, reverse=True)))
LANG = "en"


def set_lang(lang):
    global LANG
    LANG = lang if lang in LANGS else "en"


def tr(text):
    """แปลข้อความตามภาษาที่เลือก (ภาษาไทย = คืนค่าเดิม)"""
    if LANG == "th" or not isinstance(text, str) or not text:
        return text
    return _EN_RE.sub(lambda m: EN[m.group(0)], text)
